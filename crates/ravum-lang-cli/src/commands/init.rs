//! `ravum-lang init` — create a new package.
//!
//! Refuses a non-empty directory unless `--force` is given. `--force` only
//! overwrites the files this command generates; it never deletes anything and
//! never touches Git.

use std::fs;
use std::path::{Path, PathBuf};

use crate::util;

const MANIFEST: &str = "[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"core-1.0\"\n";

// Kept byte-identical to the formatter's canonical output so that
// `ravum-lang fmt --check` is clean right after `init`.
const MAIN: &str = "// Ravum Core 1.0 — generated by `ravum-lang init`.\nuse std::io;\nfn main() {\n    io::println(\"hello, ravum\");\n}\n";

const LIB: &str = "// Ravum Core 1.0 library crate — generated by `ravum-lang init`.\n\npub fn answer() -> i32 {\n    return 42;\n}\n";

pub fn run(dir: &Path, lib: bool, force: bool) -> i32 {
    if let Err(message) = create(dir, lib, force) {
        util::err(message);
        return util::EXIT_FAIL;
    }
    util::EXIT_OK
}

fn create(dir: &Path, lib: bool, force: bool) -> Result<(), String> {
    if dir.exists() {
        let meta = fs::metadata(dir)
            .map_err(|error| format!("cannot inspect `{}`: {error}", dir.display()))?;
        if !meta.is_dir() {
            return Err(format!(
                "`{}` already exists and is not a directory",
                dir.display()
            ));
        }
        let mut entries = fs::read_dir(dir)
            .map_err(|error| format!("cannot list `{}`: {error}", dir.display()))?;
        let non_empty = entries.next().is_some();
        if non_empty && !force {
            return Err(format!(
                "directory `{}` is not empty; use `ravum-lang init {} --force` to write the \
                 generated files anyway (no existing file is deleted)",
                dir.display(),
                dir.display()
            ));
        }
    } else {
        fs::create_dir_all(dir)
            .map_err(|error| format!("cannot create `{}`: {error}", dir.display()))?;
    }

    // Derive the package name from the absolute directory name so `init .`
    // does not fall back to `ravum-app`.
    let name_source = fs::canonicalize(dir).unwrap_or_else(|_| dir.to_path_buf());
    let name = derive_package_name(&name_source);
    let manifest = MANIFEST.replace("{name}", &name);
    let mut created: Vec<PathBuf> = Vec::new();

    write_generated(dir.join("ravum.toml"), &manifest, &mut created)?;
    let (source, source_kind) = if lib {
        (LIB, "src/lib.rv")
    } else {
        (MAIN, "src/main.rv")
    };
    write_generated(dir.join(source_kind), source, &mut created)?;

    let gitignore = dir.join(".gitignore");
    if !gitignore.exists() {
        write_generated(gitignore, ".ravum/\n", &mut created)?;
    }

    println!(
        "created package `{name}` in {}",
        dir.display()
    );
    for path in &created {
        println!("  {}", path.display());
    }
    println!("next: cd {} && ravum-lang check", dir.display());
    Ok(())
}

fn write_generated(path: PathBuf, contents: &str, created: &mut Vec<PathBuf>) -> Result<(), String> {
    util::write_atomic(&path, contents)?;
    created.push(path);
    Ok(())
}

/// Derive a valid `[a-z][a-z0-9_-]*` package name from the directory name.
fn derive_package_name(dir: &Path) -> String {
    let raw = dir
        .file_name()
        .map(|name| name.to_string_lossy().to_ascii_lowercase())
        .unwrap_or_default();
    let mut out = String::new();
    let mut last_separator = false;
    for ch in raw.chars() {
        if ch.is_ascii_lowercase() || ch.is_ascii_digit() {
            out.push(ch);
            last_separator = false;
        } else if !out.is_empty() && !last_separator {
            out.push('-');
            last_separator = true;
        }
    }
    while out.ends_with('-') {
        out.pop();
    }
    if out.len() > 64 {
        out.truncate(64);
        while out.ends_with('-') {
            out.pop();
        }
    }
    if out.is_empty() {
        return "ravum-app".to_string();
    }
    if !out.starts_with(|c: char| c.is_ascii_lowercase()) {
        return format!("ravum-{out}");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn derives_valid_names() {
        assert_eq!(derive_package_name(Path::new("Hello World")), "hello-world");
        assert_eq!(derive_package_name(Path::new("42-app")), "ravum-42-app");
        assert_eq!(derive_package_name(Path::new("___")), "ravum-app");
        assert_eq!(derive_package_name(Path::new("app")), "app");
    }
}
