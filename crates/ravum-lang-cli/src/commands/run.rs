//! `ravum-lang run` — build then execute the binary, forwarding stdio/args/code.
//!
//! Native targets are executed directly. `wasm32-wasip1` artifacts are executed
//! through a generated Node.js WASI preview1 launcher (no external crate, no
//! network, no preopened host directory).

use ravum_lang_sema::Profile;
use std::path::Path;
use std::process::Command;

use crate::pipeline::{self, Artifacts, BuildOptions, BuildTarget};
use crate::util;

/// Minimal WASI preview1 launcher. It is generated next to the `.wasm` file.
/// `wasi.start` runs `_start` and returns the exit code (returnOnExit).
const WASI_LAUNCHER: &str = r#"// Generated by ravum-lang — Node.js WASI preview1 launcher. Do not edit.
"use strict";
const { readFileSync } = require("node:fs");
const { WASI } = require("node:wasi");
const path = require("node:path");

async function main() {
  const wasmPath = process.argv[2];
  if (!wasmPath) {
    console.error("ravum-lang wasm launcher: missing .wasm path");
    process.exit(2);
  }
  const wasi = new WASI({
    version: "preview1",
    args: [path.basename(wasmPath, ".wasm"), ...process.argv.slice(3)],
    env: process.env,
    returnOnExit: true,
  });
  const module = await WebAssembly.compile(readFileSync(wasmPath));
  const instance = await WebAssembly.instantiate(module, wasi.getImportObject());
  let code = 0;
  try {
    code = wasi.start(instance);
  } catch (error) {
    if (error && typeof error.code === "number") {
      code = error.code;
    } else {
      console.error(error);
      code = 1;
    }
  }
  process.exit(typeof code === "number" ? code : 0);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
"#;

pub fn run(path: &Path, child_args: &[String], target: BuildTarget) -> i32 {
    // Fail fast before spending time on compilation when the runtime is absent.
    if target.is_wasm() && pipeline::node_version().is_none() {
        util::err(format!(
            "E-CLI-WASM-RUNTIME: Node.js was not found (`{}`); install Node.js 22+ or set \
             RAVUM_NODE to run wasm32-wasip1 programs",
            pipeline::node_command()
        ));
        return util::EXIT_TOOL;
    }

    let frontend = pipeline::analyze(path, Profile::Core, false);
    if !frontend.success() {
        eprint!("{}", pipeline::render_diags(&frontend));
        util::err(format!(
            "run: {} error(s); the program was not executed",
            frontend.error_count()
        ));
        return util::EXIT_FAIL;
    }

    let options = BuildOptions {
        target,
        ..BuildOptions::default()
    };
    let artifacts = match pipeline::compile_program(&frontend, &options) {
        Ok(artifacts) => artifacts,
        Err(error) => {
            error.print();
            return error.exit_code();
        }
    };

    if artifacts.target.is_wasm() {
        run_wasm(&frontend, &artifacts, child_args)
    } else {
        run_native(&frontend, &artifacts, child_args)
    }
}

fn run_native(frontend: &pipeline::Frontend, artifacts: &Artifacts, child_args: &[String]) -> i32 {
    eprintln!("running: {}", util::pretty_path(&artifacts.binary));
    let mut command = Command::new(&artifacts.binary);
    command.args(child_args);
    command.current_dir(frontend.root());
    forward_status(command.status(), &artifacts.binary)
}

fn run_wasm(frontend: &pipeline::Frontend, artifacts: &Artifacts, child_args: &[String]) -> i32 {
    let stem = artifacts
        .binary
        .file_stem()
        .map(|stem| stem.to_string_lossy().to_string())
        .unwrap_or_else(|| "program".to_string());
    let launcher = artifacts.binary.with_file_name(format!("{stem}-wasi.cjs"));
    if let Err(message) = util::write_atomic(&launcher, WASI_LAUNCHER) {
        util::err(format!("E-CLI-WASM-RUNTIME: {message}"));
        return util::EXIT_FAIL;
    }

    eprintln!(
        "running (wasm32-wasip1 via {}): {}",
        pipeline::node_command(),
        util::pretty_path(&artifacts.binary)
    );
    let mut command = Command::new(pipeline::node_command());
    command
        .arg("--experimental-wasi-unstable-preview1")
        .arg(&launcher)
        .arg(&artifacts.binary)
        .args(child_args);
    command.current_dir(frontend.root());
    match command.status() {
        Ok(status) => match status.code() {
            Some(code) => code.clamp(0, 255),
            None => {
                util::err("run: the Node.js WASI runtime was terminated by a signal");
                util::EXIT_FAIL
            }
        },
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            util::err(format!(
                "E-CLI-WASM-RUNTIME: cannot execute `{}`: {error}",
                pipeline::node_command()
            ));
            util::EXIT_TOOL
        }
        Err(error) => {
            util::err(format!(
                "E-CLI-WASM-RUNTIME: cannot execute `{}`: {error}",
                pipeline::node_command()
            ));
            util::EXIT_FAIL
        }
    }
}

fn forward_status(status: std::io::Result<std::process::ExitStatus>, binary: &Path) -> i32 {
    match status {
        Ok(status) => match status.code() {
            Some(code) => code.clamp(0, 255),
            None => {
                util::err("run: the program was terminated by a signal");
                util::EXIT_FAIL
            }
        },
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            util::err(format!(
                "run: cannot execute `{}`: {error}",
                util::pretty_path(binary)
            ));
            util::EXIT_TOOL
        }
        Err(error) => {
            util::err(format!(
                "run: cannot execute `{}`: {error}",
                util::pretty_path(binary)
            ));
            util::EXIT_FAIL
        }
    }
}
