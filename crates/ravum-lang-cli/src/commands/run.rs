//! `ravum-lang run` — build then execute the binary, forwarding stdio/args/code.
//!
//! Native targets are executed directly. `wasm32-wasip1` artifacts are executed
//! through a generated Node.js WASI preview1 launcher (no external crate, no
//! network, no preopened host directory).
//!
//! Exit codes are forwarded honestly (`child_exit_code`): a normal program code
//! `0..=255` passes through unchanged, a value above `255` is truncated to the
//! low 8 bits as POSIX shells do (a non-zero status that would truncate to `0`
//! is reported as `1` instead, so a failure is never disguised as success), and
//! a negative Windows exception/NTSTATUS is reported as `1` with its exact hex
//! code — never silently clamped to `0`.

use ravum_lang_sema::Profile;
use std::path::Path;
use std::process::{Command, Stdio};

use crate::json;
use crate::pipeline::{self, Artifacts, BuildOptions, BuildTarget};
use crate::util;

/// Minimal WASI preview1 launcher. It is generated next to the `.wasm` file.
/// `wasi.start` runs `_start` and returns the exit code (returnOnExit).
const WASI_LAUNCHER: &str = r#"// Generated by ravum-lang — Node.js WASI preview1 launcher. Do not edit.
"use strict";
const { readFileSync } = require("node:fs");
const { WASI } = require("node:wasi");
const path = require("node:path");

async function main() {
  const wasmPath = process.argv[2];
  if (!wasmPath) {
    console.error("ravum-lang wasm launcher: missing .wasm path");
    process.exit(2);
  }
  const wasi = new WASI({
    version: "preview1",
    args: [path.basename(wasmPath, ".wasm"), ...process.argv.slice(3)],
    env: process.env,
    returnOnExit: true,
  });
  const module = await WebAssembly.compile(readFileSync(wasmPath));
  const instance = await WebAssembly.instantiate(module, wasi.getImportObject());
  let code = 0;
  try {
    code = wasi.start(instance);
  } catch (error) {
    if (error && typeof error.code === "number") {
      code = error.code;
    } else {
      console.error(error);
      code = 1;
    }
  }
  process.exit(typeof code === "number" ? code : 0);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
"#;

/// How `run` reports. Without `--json` the CLI prints diagnostics on stderr
/// and lets the program write to the terminal. With `--json` (DIAG-8.1,
/// D-18-5) stdout carries exactly one JSON object (DIAG-7.1): the program's
/// own stdout is forwarded to stderr, and the object gives `status`,
/// `exit_code` and, in `summary`, whether the program ran and its exit code.
struct Report<'a> {
    path: &'a Path,
    json: bool,
}

impl Report<'_> {
    /// A failure before the program ran (frontend, build or runtime lookup).
    fn not_run(
        &self,
        frontend: Option<&pipeline::Frontend>,
        exit_code: i32,
        diagnostics: Vec<json::JsonDiagnostic>,
    ) -> i32 {
        if self.json {
            let mut summary = frontend
                .map(|f| pipeline::base_summary(f, Profile::Core))
                .unwrap_or_else(|| serde_json::json!({}));
            summary["executed"] = serde_json::json!(false);
            summary["program_exit_code"] = serde_json::Value::Null;
            json::print(&self.envelope(frontend, exit_code, diagnostics, summary));
        }
        exit_code
    }

    /// The program ran and returned `exit`.
    fn ran(&self, frontend: &pipeline::Frontend, exit: ChildExit, context: &str) -> i32 {
        if let Some(note) = &exit.note {
            util::err(format!("{context} {note}"));
        }
        if self.json {
            let mut summary = pipeline::base_summary(frontend, Profile::Core);
            summary["executed"] = serde_json::json!(true);
            summary["program_exit_code"] = serde_json::json!(exit.code);
            if let Some(note) = &exit.note {
                summary["program_exit_note"] = serde_json::json!(note);
            }
            json::print(&self.envelope(Some(frontend), exit.code, Vec::new(), summary));
        }
        exit.code
    }

    fn envelope(
        &self,
        frontend: Option<&pipeline::Frontend>,
        exit_code: i32,
        diagnostics: Vec<json::JsonDiagnostic>,
        summary: serde_json::Value,
    ) -> json::JsonEnvelope {
        use ravum_lang_sema::loader::{CrateKind, LockfileState};
        let target_kind = match frontend {
            Some(f) if f.pkg.crate_kind == Some(CrateKind::File) => "file",
            _ => "package",
        };
        let lockfile_stale = frontend.and_then(|f| match f.pkg.lockfile_state {
            LockfileState::Stale => Some(true),
            LockfileState::Created | LockfileState::Current => Some(false),
            _ => None,
        });
        json::envelope(
            json::ReportMeta {
                command: "run",
                success: exit_code == util::EXIT_OK,
                exit_code,
                target_kind,
                target_path: util::target_display(self.path),
                profile: Some("core".to_string()),
                dependencies_digest: frontend.map(|f| f.pkg.dependencies_digest.clone()),
                lockfile_stale,
            },
            diagnostics,
            summary,
        )
    }

    /// Where the program's stdout goes: the terminal, or stderr under `--json`.
    fn program_stdout(&self) -> Stdio {
        if self.json {
            Stdio::from(std::io::stderr())
        } else {
            Stdio::inherit()
        }
    }

    /// A tool error message: on stderr, and as a diagnostic under `--json`.
    fn tool_error(
        &self,
        frontend: Option<&pipeline::Frontend>,
        code: &str,
        message: String,
        exit_code: i32,
    ) -> i32 {
        util::err(&message);
        self.not_run(
            frontend,
            exit_code,
            vec![json::synthetic(code, "error", message)],
        )
    }
}

pub fn run(
    path: &Path,
    child_args: &[String],
    target: BuildTarget,
    json_output: bool,
    det_seed: Option<u64>,
    journal: Option<&crate::args::Journal>,
) -> i32 {
    let report = Report {
        path,
        json: json_output,
    };
    // Fail fast before spending time on compilation when the runtime is absent.
    if target.is_wasm() && pipeline::node_version().is_none() {
        return report.tool_error(
            None,
            "E-CLI-WASM-RUNTIME",
            format!(
                "E-CLI-WASM-RUNTIME: Node.js was not found (`{}`); install Node.js 22+ or set \
                 RAVUM_NODE to run wasm32-wasip1 programs",
                pipeline::node_command()
            ),
            util::EXIT_TOOL,
        );
    }

    // `det` (DET-1): the program must not reach an input it cannot replay;
    // the run itself is scheduled by the seed (DET-3).
    let profile = match (det_seed, journal) {
        (Some(_), Some(_)) => Profile::DetIo,
        (Some(_), None) => Profile::Det,
        _ => Profile::Core,
    };
    let frontend = pipeline::analyze(path, profile, false);
    if !frontend.success() {
        if json_output {
            let diagnostics = json::diagnostics(frontend.diags.as_slice(), &frontend.pkg.sources);
            return report.not_run(Some(&frontend), util::EXIT_FAIL, diagnostics);
        }
        eprint!("{}", pipeline::render_diags(&frontend));
        util::err(format!(
            "run: {} error(s); the program was not executed",
            frontend.error_count()
        ));
        return util::EXIT_FAIL;
    }

    let options = BuildOptions {
        target,
        ..BuildOptions::default()
    };
    let artifacts = match pipeline::compile_program(&frontend, &options) {
        Ok(artifacts) => artifacts,
        Err(error) => {
            error.print();
            let diagnostic = json::synthetic("E-BUILD", "error", error.message());
            return report.not_run(Some(&frontend), error.exit_code(), vec![diagnostic]);
        }
    };

    if artifacts.target.is_wasm() {
        run_wasm(&report, &frontend, &artifacts, child_args)
    } else {
        run_native(
            &report, &frontend, &artifacts, child_args, det_seed, journal,
        )
    }
}

fn run_native(
    report: &Report<'_>,
    frontend: &pipeline::Frontend,
    artifacts: &Artifacts,
    child_args: &[String],
    det_seed: Option<u64>,
    journal: Option<&crate::args::Journal>,
) -> i32 {
    eprintln!("running: {}", util::pretty_path(&artifacts.binary));
    let mut command = Command::new(&artifacts.binary);
    command.args(child_args);
    for var in [
        "RAVUM_DET_SEED",
        "RAVUM_DET_RECORD",
        "RAVUM_DET_REPLAY",
        "RAVUM_DET_HEADER",
    ] {
        command.env_remove(var);
    }
    let mut det_seed = det_seed;
    if let Some(journal) = journal {
        // DET-13: the header binds a journal to this binary and platform.
        let binary = match std::fs::read(&artifacts.binary) {
            Ok(bytes) => ravum_lang_sema::loader::sha256_hex(&bytes),
            Err(error) => {
                util::err(format!("run: cannot read the built program: {error}"));
                return util::EXIT_TOOL;
            }
        };
        let platform = format!("{}-{}", std::env::consts::OS, std::env::consts::ARCH);
        let absolute = |p: &Path| {
            if p.is_absolute() {
                p.to_path_buf()
            } else {
                std::env::current_dir().unwrap_or_default().join(p)
            }
        };
        match journal {
            crate::args::Journal::Record(path) => {
                let seed = det_seed.unwrap_or(0);
                let header = format!(
                    "ravum-rvlog-1\tseed={seed}\tbinary=sha256:{binary}\tplatform={platform}"
                );
                // DET-14: the journal holds what the program read.
                eprintln!(
                    "profile det: recording I/O to {} (it contains the data the program reads)",
                    util::pretty_path(path)
                );
                command.env("RAVUM_DET_RECORD", absolute(path));
                command.env("RAVUM_DET_HEADER", header);
            }
            crate::args::Journal::Replay(path) => {
                let text = match std::fs::read_to_string(path) {
                    Ok(text) => text,
                    Err(error) => {
                        util::err(format!(
                            "run: cannot read the journal `{}`: {error}",
                            util::pretty_path(path)
                        ));
                        return util::EXIT_USAGE;
                    }
                };
                let header = text.lines().next().unwrap_or("");
                let fields: Vec<&str> = header.split('\t').collect();
                let seed = fields
                    .iter()
                    .find_map(|f| f.strip_prefix("seed="))
                    .and_then(|s| s.parse::<u64>().ok());
                let expected_binary = format!("binary=sha256:{binary}");
                let expected_platform = format!("platform={platform}");
                let matches = fields.first() == Some(&"ravum-rvlog-1")
                    && fields.contains(&expected_binary.as_str())
                    && fields.contains(&expected_platform.as_str());
                match (seed, matches) {
                    (Some(seed), true) => {
                        det_seed = Some(seed);
                        eprintln!(
                            "profile det: replaying I/O from {}",
                            util::pretty_path(path)
                        );
                        command.env("RAVUM_DET_REPLAY", absolute(path));
                    }
                    _ => {
                        util::err(format!(
                            "run: the journal `{}` was not recorded by this program on this \
                             platform (header `{header}`); refusing to replay (DET-13)",
                            util::pretty_path(path)
                        ));
                        return util::EXIT_USAGE;
                    }
                }
            }
        }
    }
    if let Some(seed) = det_seed {
        eprintln!("profile det: seed={seed}");
        command.env("RAVUM_DET_SEED", seed.to_string());
    }
    command.current_dir(frontend.root());
    command.stdout(report.program_stdout());
    // V2-K1: an interrupted `run` (SIGINT/SIGTERM, console Ctrl+C) stops the
    // program it launched instead of leaving it running. SIGKILL cannot be
    // caught by any process: the child then survives (documented limit).
    super::watch::install_interrupt_handler();
    let status = command.spawn().and_then(|mut child| loop {
        if let Some(status) = child.try_wait()? {
            break Ok(status);
        }
        if super::watch::interrupt_requested() {
            let _ = child.kill();
            let _ = child.wait();
            break Err(std::io::Error::new(
                std::io::ErrorKind::Interrupted,
                "interrupted; the program was stopped",
            ));
        }
        std::thread::sleep(std::time::Duration::from_millis(20));
    });
    match status {
        Err(error) if error.kind() == std::io::ErrorKind::Interrupted => {
            util::err("run: interrupted; the program was stopped");
            130
        }
        Ok(status) => report.ran(frontend, child_exit_code(status.code()), "run: the program"),
        Err(error) => {
            let exit = if error.kind() == std::io::ErrorKind::NotFound {
                util::EXIT_TOOL
            } else {
                util::EXIT_FAIL
            };
            report.tool_error(
                Some(frontend),
                "E-TOOL",
                format!(
                    "run: cannot execute `{}`: {error}",
                    util::pretty_path(&artifacts.binary)
                ),
                exit,
            )
        }
    }
}

fn run_wasm(
    report: &Report<'_>,
    frontend: &pipeline::Frontend,
    artifacts: &Artifacts,
    child_args: &[String],
) -> i32 {
    let stem = artifacts
        .binary
        .file_stem()
        .map(|stem| stem.to_string_lossy().to_string())
        .unwrap_or_else(|| "program".to_string());
    let launcher = artifacts.binary.with_file_name(format!("{stem}-wasi.cjs"));
    if let Err(message) = util::write_atomic(&launcher, WASI_LAUNCHER) {
        return report.tool_error(
            Some(frontend),
            "E-CLI-WASM-RUNTIME",
            format!("E-CLI-WASM-RUNTIME: {message}"),
            util::EXIT_FAIL,
        );
    }

    eprintln!(
        "running (wasm32-wasip1 via {}): {}",
        pipeline::node_command(),
        util::pretty_path(&artifacts.binary)
    );
    let mut command = Command::new(pipeline::node_command());
    command
        .arg("--experimental-wasi-unstable-preview1")
        .arg(&launcher)
        .arg(&artifacts.binary)
        .args(child_args);
    command.current_dir(frontend.root());
    command.stdout(report.program_stdout());
    match command.status() {
        Ok(status) => report.ran(
            frontend,
            child_exit_code(status.code()),
            "run: the Node.js WASI runtime",
        ),
        Err(error) => {
            let exit = if error.kind() == std::io::ErrorKind::NotFound {
                util::EXIT_TOOL
            } else {
                util::EXIT_FAIL
            };
            report.tool_error(
                Some(frontend),
                "E-CLI-WASM-RUNTIME",
                format!(
                    "E-CLI-WASM-RUNTIME: cannot execute `{}`: {error}",
                    pipeline::node_command()
                ),
                exit,
            )
        }
    }
}

/// The exit code the CLI returns for a child process, with an honest note when
/// the raw status cannot be forwarded verbatim.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ChildExit {
    pub code: i32,
    pub note: Option<String>,
}

/// Map a raw child status code to the CLI exit code.
///
/// * `None` — killed without an exit code (a signal on Unix, an unknown
///   termination on Windows). Reported as `1`, never `0`.
/// * `Some(0)` — success.
/// * `Some(1..=255)` — a normal program code, forwarded verbatim.
/// * `Some(code)` with `code > 255` — the low 8 bits, as POSIX shells truncate
///   (`code & 0xFF`), with a note. If the truncated value is `0`, the CLI
///   reports `1` instead: a non-zero program status is never turned into a
///   success by truncation. This arm is only *reachable* where the parent
///   observes the full 32-bit status (Windows): on POSIX `waitpid` already
///   reports `code & 0xFF`, so `_exit(300)` arrives as `44` and `_exit(256)` as
///   `0` — the CLI forwards what the kernel reports and prints no note, because
///   it never saw the original value. That limitation is the platform's, and it
///   is documented in `README.md`; see `tests/exit_codes.rs` for both halves of
///   the contract.
/// * `Some(code)` with `code < 0` — a Windows exception/NTSTATUS (for example
///   `-1073741819` is `0xC0000005`, access violation). Reported as `1` with the
///   exact 32-bit hex code; `clamp(0, 255)` must never turn it into `0`.
pub(crate) fn child_exit_code(raw: Option<i32>) -> ChildExit {
    match raw {
        None => ChildExit {
            code: util::EXIT_FAIL,
            note: Some(
                "was terminated without an exit code (signal or abrupt termination); \
                 reporting exit code 1"
                    .to_string(),
            ),
        },
        Some(0) => ChildExit {
            code: util::EXIT_OK,
            note: None,
        },
        Some(code) if (1..=255).contains(&code) => ChildExit { code, note: None },
        Some(code) if code > 255 => {
            let low = code & 0xFF;
            if low == 0 {
                ChildExit {
                    code: util::EXIT_FAIL,
                    note: Some(format!(
                        "exited with status {code}; POSIX truncates statuses to 8 bits ({low}), \
                         which would report success — reporting exit code 1 instead"
                    )),
                }
            } else {
                ChildExit {
                    code: low,
                    note: Some(format!(
                        "exited with status {code}; POSIX truncates statuses to 8 bits, \
                         reporting {low}"
                    )),
                }
            }
        }
        Some(code) => ChildExit {
            code: util::EXIT_FAIL,
            note: Some(format!(
                "was terminated by exception 0x{:08X}{}; reporting exit code 1",
                code as u32,
                exception_name(code)
            )),
        },
    }
}

/// Short name for the Windows exceptions most often seen from a Ravum program.
fn exception_name(code: i32) -> &'static str {
    match code as u32 {
        0xC000_0005 => " (access violation)",
        0xC000_001D => " (illegal instruction)",
        0xC000_0094 => " (integer division by zero)",
        0xC000_00FD => " (stack overflow)",
        0xC000_013A => " (control-C / break)",
        0xC000_0409 => " (abort / stack buffer overrun)",
        _ => "",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn success_is_zero() {
        let exit = child_exit_code(Some(0));
        assert_eq!(exit.code, 0);
        assert!(exit.note.is_none());
    }

    #[test]
    fn ordinary_program_codes_pass_through() {
        for code in [1, 2, 3, 7, 42, 127, 255] {
            let exit = child_exit_code(Some(code));
            assert_eq!(exit.code, code, "code {code}");
            assert!(exit.note.is_none(), "code {code} should need no note");
        }
    }

    #[test]
    fn windows_access_violation_is_never_success() {
        // 0xC0000005 as Windows reports it through `ExitStatus::code()`.
        let exit = child_exit_code(Some(-1073741819));
        assert_eq!(exit.code, 1);
        let note = exit.note.expect("an exception must be explained");
        assert!(note.contains("0xC0000005"), "note: {note}");
        assert!(note.contains("access violation"), "note: {note}");
    }

    #[test]
    fn windows_control_c_is_never_success() {
        // 0xC000013A = STATUS_CONTROL_C_EXIT.
        let exit = child_exit_code(Some(-1073741510));
        assert_eq!(exit.code, 1);
        let note = exit.note.expect("an exception must be explained");
        assert!(note.contains("0xC000013A"), "note: {note}");
    }

    #[test]
    fn negative_codes_always_report_failure() {
        for code in [-1, -2, i32::MIN, -1073741819, -1073741510] {
            let exit = child_exit_code(Some(code));
            assert_eq!(exit.code, 1, "raw code {code}");
            assert!(exit.note.as_deref().is_some_and(|n| n.contains("0x")));
        }
    }

    #[test]
    fn no_exit_code_is_a_failure() {
        let exit = child_exit_code(None);
        assert_eq!(exit.code, 1);
        assert!(exit.note.is_some());
    }

    #[test]
    fn above_255_is_truncated_like_posix() {
        let exit = child_exit_code(Some(300));
        assert_eq!(exit.code, 44);
        let note = exit.note.expect("truncation must be explained");
        assert!(note.contains("300"), "note: {note}");
    }

    #[test]
    fn truncation_never_turns_a_failure_into_success() {
        // 256 & 0xFF == 0: POSIX would report success, which would be a lie.
        let exit = child_exit_code(Some(256));
        assert_eq!(exit.code, 1);
        let note = exit.note.expect("the substitution must be explained");
        assert!(note.contains("256"), "note: {note}");
        assert!(note.contains("exit code 1"), "note: {note}");
    }
}
