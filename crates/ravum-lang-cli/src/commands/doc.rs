//! `ravum-lang doc` — Markdown API documentation from the AST.
//!
//! Public items only. No HTML, no template engine. Doc comments are not part of
//! the Core 1.0 AST, so signatures/effects are documented, not prose.

use ravum_lang_sema::loader::{load_package, CrateKind, LoadedPackage};
use ravum_lang_syntax::ast::{
    FieldDef, FnItem, ItemKind, Module, ParamKind, Receiver, Type, TypeKind,
    VariantDefFields,
};
use std::fs;
use std::path::{Path, PathBuf};

use crate::util;

pub fn run(path: &Path, out: Option<&Path>) -> i32 {
    let package = load_package(path);
    if package.diags.has_errors() {
        eprint!("{}", package.diags.render(&package.sources));
        util::err(format!(
            "doc: {} error(s); no documentation was generated",
            package.diags.error_count()
        ));
        return util::EXIT_FAIL;
    }

    let root = PathBuf::from(&package.root_dir);
    let out_dir = match out {
        Some(dir) => {
            if let Err(message) = fs::create_dir_all(dir) {
                util::err(format!("cannot create `{}`: {message}", util::pretty_path(dir)));
                return util::EXIT_FAIL;
            }
            dir.to_path_buf()
        }
        None => match util::ensure_cache_dir(&root) {
            Ok(cache) => {
                let dir = cache.join("doc");
                if let Err(message) = fs::create_dir_all(&dir) {
                    util::err(format!("cannot create `{}`: {message}", util::pretty_path(&dir)));
                    return util::EXIT_FAIL;
                }
                dir
            }
            Err(message) => {
                util::err(message);
                return util::EXIT_FAIL;
            }
        },
    };

    let markdown = render_documentation(&package);
    let target = out_dir.join("index.md");
    if let Err(message) = util::write_atomic(&target, &markdown) {
        util::err(message);
        return util::EXIT_FAIL;
    }
    println!("wrote {}", util::pretty_path(&target));
    util::EXIT_OK
}

fn render_documentation(package: &LoadedPackage) -> String {
    let name = package.package_name.as_deref().unwrap_or("<unknown>");
    let mut md = String::new();
    md.push_str(&format!("# `{name}` — Ravum API documentation\n\n"));
    md.push_str(
        "> Generated by `ravum-lang doc` from Ravum Core 1.0 sources. Public items only.\n\
         > Doc comments are not represented in the Core 1.0 AST in this build.\n\n",
    );

    if let Some(program) = &package.program {
        let kind = package.crate_kind.unwrap_or(CrateKind::Bin);
        render_crate(&mut md, kind, program, name);
    }
    if let Some(program) = &package.lib_program {
        render_crate(&mut md, CrateKind::Lib, program, name);
    }
    if package.program.is_none() && package.lib_program.is_none() {
        md.push_str("_No crate root was loaded._\n");
    }
    md
}

fn render_crate(
    md: &mut String,
    kind: CrateKind,
    program: &ravum_lang_syntax::ast::Program,
    package: &str,
) {
    md.push_str(&format!(
        "## Crate `{}` — `{}`\n\n",
        kind.name(),
        match kind {
            CrateKind::Bin => "src/main.rv",
            CrateKind::Lib => "src/lib.rv",
            CrateKind::File => "standalone file",
        }
    ));
    md.push_str(&format!("Package `{package}`.\n\n"));
    render_module(md, &program.root, "crate", 3);
}

fn render_module(md: &mut String, module: &Module, path: &str, level: usize) {
    let module_path = match &module.name {
        Some(name) => format!("{path}::{}", name.name),
        None => path.to_string(),
    };
    if module.name.is_some() {
        md.push_str(&format!(
            "{} Module `{}`\n\n",
            "#".repeat(level.min(6)),
            module_path
        ));
    }

    let mut functions: Vec<&FnItem> = Vec::new();
    let mut structs = Vec::new();
    let mut enums = Vec::new();
    let mut consts = Vec::new();
    let mut impls = Vec::new();
    let mut modules: Vec<&Module> = Vec::new();

    for item in &module.items {
        if !item.vis.is_public() {
            continue;
        }
        match &item.kind {
            ItemKind::Fn(function) => {
                if !function.is_test {
                    functions.push(function);
                }
            }
            ItemKind::Struct(definition) => structs.push(definition),
            ItemKind::Enum(definition) => enums.push(definition),
            ItemKind::Const(definition) => consts.push(definition),
            ItemKind::Impl(implementation) => impls.push(implementation),
            ItemKind::Mod(inner) => {
                // Dependency wrapper modules are synthesised with a dummy span;
                // they are not part of this package's API.
                if !item.span.is_dummy() {
                    modules.push(inner);
                }
            }
            ItemKind::Use(_) | ItemKind::ModDecl(_) => {}
        }
    }

    if !functions.is_empty() {
        md.push_str(&format!("{} Functions\n\n", "#".repeat((level + 1).min(6))));
        for function in functions {
            md.push_str(&format!("- `{}`\n", render_fn(function, true)));
        }
        md.push('\n');
    }
    if !structs.is_empty() {
        md.push_str(&format!("{} Structs\n\n", "#".repeat((level + 1).min(6))));
        for definition in structs {
            let fields = render_public_fields(&definition.fields);
            if fields.is_empty() {
                md.push_str(&format!("- `pub struct {}`\n", definition.name.name));
            } else {
                md.push_str(&format!(
                    "- `pub struct {} {{ {} }}`\n",
                    definition.name.name,
                    fields
                ));
            }
        }
        md.push('\n');
    }
    if !enums.is_empty() {
        md.push_str(&format!("{} Enums\n\n", "#".repeat((level + 1).min(6))));
        for definition in enums {
            let variants = definition
                .variants
                .iter()
                .map(|variant| match &variant.fields {
                    VariantDefFields::Unit => variant.name.name.clone(),
                    VariantDefFields::Tuple(types) => format!(
                        "{}({})",
                        variant.name.name,
                        types
                            .iter()
                            .map(render_type)
                            .collect::<Vec<_>>()
                            .join(", ")
                    ),
                    VariantDefFields::Struct(fields) => {
                        format!(
                            "{} {{ {} }}",
                            variant.name.name,
                            render_public_fields(fields)
                        )
                    }
                })
                .collect::<Vec<_>>()
                .join(", ");
            md.push_str(&format!(
                "- `pub enum {} {{ {variants} }}`\n",
                definition.name.name
            ));
        }
        md.push('\n');
    }
    if !consts.is_empty() {
        md.push_str(&format!("{} Constants\n\n", "#".repeat((level + 1).min(6))));
        for definition in consts {
            md.push_str(&format!(
                "- `pub const {}: {}`\n",
                definition.name.name,
                render_type(&definition.ty)
            ));
        }
        md.push('\n');
    }
    if !impls.is_empty() {
        for implementation in impls {
            let methods: Vec<&FnItem> = implementation
                .items
                .iter()
                .filter(|item| item.vis.is_public())
                .filter_map(|item| match &item.kind {
                    ItemKind::Fn(function) if !function.is_test => Some(function),
                    _ => None,
                })
                .collect();
            if methods.is_empty() {
                continue;
            }
            md.push_str(&format!(
                "{} Methods of `{}`\n\n",
                "#".repeat((level + 1).min(6)),
                render_type(&implementation.self_ty)
            ));
            for method in methods {
                md.push_str(&format!("- `{}`\n", render_fn(method, true)));
            }
            md.push('\n');
        }
    }
    for inner in modules {
        render_module(md, inner, &module_path, level + 1);
    }
}

fn render_public_fields(fields: &[FieldDef]) -> String {
    fields
        .iter()
        .filter(|field| field.vis.is_public())
        .map(|field| format!("pub {}: {}", field.name.name, render_type(&field.ty)))
        .collect::<Vec<_>>()
        .join(", ")
}

fn render_fn(function: &FnItem, public: bool) -> String {
    let mut out = String::new();
    if public {
        out.push_str("pub ");
    }
    out.push_str("fn ");
    out.push_str(&function.name.name);
    if !function.generics.is_empty() {
        out.push('<');
        out.push_str(
            &function
                .generics
                .iter()
                .map(|generic| generic.name.name.clone())
                .collect::<Vec<_>>()
                .join(", "),
        );
        out.push('>');
    }
    out.push('(');
    out.push_str(
        &function
            .params
            .iter()
            .map(|param| match &param.kind {
                ParamKind::Receiver(receiver) => match receiver {
                    Receiver::Shared => "&self".to_string(),
                    Receiver::Exclusive => "&mut self".to_string(),
                    Receiver::ByValue => "self".to_string(),
                },
                ParamKind::Binding { name, ty } => {
                    format!("{}: {}", name.name, render_type(ty))
                }
            })
            .collect::<Vec<_>>()
            .join(", "),
    );
    out.push(')');
    if !matches!(function.ret.kind, TypeKind::Unit) {
        out.push_str(" -> ");
        out.push_str(&render_type(&function.ret));
    }
    match &function.effects {
        None => out.push_str(" — effects: inferred"),
        Some(effects) if effects.is_empty() => out.push_str(" — effects: pure"),
        Some(effects) => out.push_str(&format!(
            " — effects: {}",
            effects
                .iter()
                .map(|effect| effect.name.clone())
                .collect::<Vec<_>>()
                .join(", ")
        )),
    }
    out
}

fn render_type(ty: &Type) -> String {
    match &ty.kind {
        TypeKind::Path(path) => {
            let mut out = String::new();
            match path.root {
                ravum_lang_syntax::ast::PathRoot::Crate => out.push_str("crate::"),
                ravum_lang_syntax::ast::PathRoot::Super => out.push_str("super::"),
                ravum_lang_syntax::ast::PathRoot::SelfMod => out.push_str("self::"),
                ravum_lang_syntax::ast::PathRoot::Plain => {}
            }
            out.push_str(
                &path
                    .segments
                    .iter()
                    .map(|segment| {
                        if segment.args.is_empty() {
                            segment.name.name.clone()
                        } else {
                            format!(
                                "{}<{}>",
                                segment.name.name,
                                segment
                                    .args
                                    .iter()
                                    .map(render_type)
                                    .collect::<Vec<_>>()
                                    .join(", ")
                            )
                        }
                    })
                    .collect::<Vec<_>>()
                    .join("::"),
            );
            out
        }
        TypeKind::Ref { mutable, inner } => {
            if *mutable {
                format!("&mut {}", render_type(inner))
            } else {
                format!("&{}", render_type(inner))
            }
        }
        TypeKind::Tuple(types) => format!(
            "({})",
            types.iter().map(render_type).collect::<Vec<_>>().join(", ")
        ),
        TypeKind::Array { elem, len } => {
            format!("[{}; {}]", render_type(elem), render_expr(len))
        }
        TypeKind::Slice(inner) => format!("[{}]", render_type(inner)),
        TypeKind::Unit => "()".to_string(),
        TypeKind::Infer => "_".to_string(),
        TypeKind::SelfType => "Self".to_string(),
    }
}

fn render_expr(expr: &ravum_lang_syntax::ast::Expr) -> String {
    match &expr.kind {
        ravum_lang_syntax::ast::ExprKind::Int { value, .. } => value.to_string(),
        _ => "_".to_string(),
    }
}
