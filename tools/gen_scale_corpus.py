#!/usr/bin/env python3
"""Generate a deterministic, valid Ravum package of a requested size.

Why this exists
---------------
Every example in ``examples/`` is 5 to 338 lines, so no published measurement
says anything about a real package. This generator builds a *valid* Core 1.0
package (``ravum.toml``, ``src/main.rv``, ``src/mK.rv``) where:

* every module ``mK`` declares one struct ``ItemK`` and ``F`` functions;
* the functions of a module call each other in a chain;
* the first function of module ``K`` calls the first function of module
  ``K - 1`` (``crate::m{K-1}::f{K-1}_0``), so the call graph crosses modules;
* ``main`` calls the last function of the last module and prints the result.

The output is deterministic: no randomness, no timestamps. The reported line
count is the number of physical lines of every ``.rv`` file plus the manifest.

Usage
-----
    python tools/gen_scale_corpus.py --modules 40 --fns 4 --out target/scale-1k
    python tools/gen_scale_corpus.py --modules 1000 --fns 1 --out target/scale-1000-files

``--modules`` is capped at 150 for *measurement* runs while
``MAX_SOURCE_FILES`` is 200 (``ravum-lang-sema/src/loader.rs``): the manifest and
the lock file also count. The script itself accepts any ``M`` so the 1 000-file
package can be generated once the cap is raised; it warns above 150.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "core-1.0"
"""

MAIN_HEAD = """use std::io;

"""

MAIN_BODY = """fn main() {{
    let value = crate::m{last}::f{last}_{last_fn}(1);
    io::println(&value.to_string());
}}
"""


def module_source(index: int, fns: int) -> str:
    """One module: a struct plus `fns` chained functions."""
    lines = [
        f"// module m{index} — deterministic, generated by tools/gen_scale_corpus.py.",
        f"pub struct Item{index} {{ a: i32, b: i32 }}",
        "",
        f"pub fn f{index}_0(x: i32) -> i32 {{",
        f"    let item = Item{index} {{ a: x, b: {index} }};",
    ]
    if index == 0:
        lines.append("    return item.a + item.b;")
    else:
        lines.append(f"    let previous = crate::m{index - 1}::f{index - 1}_0(x);")
        lines.append("    return item.a + item.b + previous;")
    lines.append("}")
    lines.append("")
    for step in range(1, fns):
        lines.extend(
            [
                f"pub fn f{index}_{step}(x: i32) -> i32 {{",
                f"    let value = f{index}_{step - 1}(x) + {step};",
                f"    return value + {index};",
                "}",
                "",
            ]
        )
    return "\n".join(lines)


def build(modules: int, fns: int, out: Path) -> dict[str, int]:
    if modules < 1:
        raise SystemExit("--modules must be >= 1")
    if fns < 1:
        raise SystemExit("--fns must be >= 1")
    if out.exists():
        shutil.rmtree(out)
    src = out / "src"
    src.mkdir(parents=True)
    name = f"scale-m{modules}-f{fns}"
    (out / "ravum.toml").write_text(MANIFEST.format(name=name), encoding="utf-8")

    decls = "\n".join(f"mod m{index};" for index in range(modules))
    last = modules - 1
    main = MAIN_HEAD + decls + "\n\n" + MAIN_BODY.format(last=last, last_fn=fns - 1)
    (src / "main.rv").write_text(main, encoding="utf-8")
    for index in range(modules):
        (src / f"m{index}.rv").write_text(module_source(index, fns), encoding="utf-8")

    total = 0
    for path in out.rglob("*.rv"):
        total += len(path.read_text(encoding="utf-8").splitlines())
    total += len((out / "ravum.toml").read_text(encoding="utf-8").splitlines())
    return {"modules": modules, "fns": fns, "files": modules + 2, "lines": total}


PRESETS = {
    "1000": (35, 5),
    "5000": (150, 6),
    "20000": (150, 26),
    "50000": (150, 66),
    "files1000": (1000, 1),
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--modules", type=int, help="number of modules (src/mK.rv)")
    parser.add_argument("--fns", type=int, help="functions per module")
    parser.add_argument("--out", type=Path, required=True, help="package directory to write")
    parser.add_argument(
        "--preset",
        choices=sorted(PRESETS),
        help="use a named (modules, fns) preset instead of explicit values",
    )
    args = parser.parse_args()

    if args.preset:
        modules, fns = PRESETS[args.preset]
    elif args.modules is not None and args.fns is not None:
        modules, fns = args.modules, args.fns
    else:
        parser.error("give --modules and --fns, or --preset")

    if modules > 150:
        print(
            "warning: more than 150 modules: MAX_SOURCE_FILES is 200 today, so "
            "the package can only be loaded once the cap is raised",
            file=sys.stderr,
        )
    stats = build(modules, fns, args.out)
    print(
        "generated {files} files ({modules} modules, {fns} functions each): "
        "{lines} lines in {out}".format(out=args.out, **stats)
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
